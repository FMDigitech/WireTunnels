#!/usr/bin/env bash
# generate_tool_anchors.sh
# Xcode build phase of the WireTunnelsHelper target, before Compile Sources.
# Compiles the hash of the patched wg-quick into the helper, so the helper checks
# the tools it installs against its own anchor instead of anything in the bundle.
# wg and wireguard-go are checked by code signature, which survives re-signing.

set -euo pipefail

SRCROOT="${SRCROOT:-.}"
CACHE_DIR="${SRCROOT}/build/wireguard-cache"
SWIFT_OUT="${BUILT_PRODUCTS_DIR:?}/ToolAnchors/ToolAnchors.generated.swift"
HASH_OUT="${BUILT_PRODUCTS_DIR:?}/ToolAnchors/wg-quick.sha256"

bash "${SRCROOT}/Scripts/build_wireguard_binaries.sh" --prepare-wg-quick
hash=$(shasum -a 256 "${CACHE_DIR}/wg-quick" | awk '{print $1}')

mkdir -p "$(dirname "$SWIFT_OUT")" "$(dirname "$HASH_OUT")"
cat > "${SWIFT_OUT}.tmp" <<SWIFT
// Generated by Scripts/generate_tool_anchors.sh. Do not edit.
enum ToolAnchors {
    static let wgQuickSHA256 = "${hash}"
}
SWIFT
mv "${SWIFT_OUT}.tmp" "$SWIFT_OUT"
# The app's copy step checks the bundled wg-quick against this.
printf '%s\n' "$hash" > "$HASH_OUT"
